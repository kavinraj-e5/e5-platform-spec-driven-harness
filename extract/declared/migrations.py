"""Tables and column changes, from Flyway migrations.

A HYBRID, AND THE RATIO IS A FACT
---------------------------------
sqlglot is the right tool for the 80% and cannot do the rest. Measured across the
estate's migrations: **46 statements fall back to sqlglot's opaque `Command`**, and 11
of them are `CREATE TABLE`s in deployment-mgmt — every table whose DDL was generated by
pgAdmin and so carries `COLLATE pg_catalog."default"` and `TABLESPACE pg_default`. One
file (`workflow-api V9__...sql`) does not parse at all.

So a pure-sqlglot port would LOSE eleven tables. Instead each statement is tried
against the parser and, when the parser produces `Command` or nothing, against the
regex this replaces — on **that statement's text alone**, which is the part the old
extractor could not do because it ran over the whole file at once.

Every fact says which path produced it (`parsed_by`), and each file emits a
`SqlParseGap` carrying the count. A degradation nobody counts is a degradation nobody
fixes: `./e5 estate diff` will show the number moving when a sqlglot release widens its
PostgreSQL support, and that is the signal to delete the fallback.
"""
from __future__ import annotations

import re

from extract.core import Repo, fact
from extract.parse.sqlfile import blank_strings, statements

from sqlglot import exp

# The fallback. Identical to the regex that was here, with one difference that matters:
# it now runs on ONE statement, already comment-blanked and already split on real
# statement boundaries, so `finditer` cannot skip past a statement it half-matched.
_CREATE = re.compile(
    r'CREATE\s+(?:UNLOGGED\s+|TEMP(?:ORARY)?\s+)?TABLE\s+'
    r'(?:IF\s+NOT\s+EXISTS\s+)?[`"\[]?([A-Za-z_][\w.]*)[`"\]]?', re.I)
_ALTER = re.compile(
    r'ALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?[`"\[]?([A-Za-z_][\w.]*)[`"\]]?\s+'
    r'(ADD|DROP)\s+(?:COLUMN\s+)?(?:IF\s+(?:NOT\s+)?EXISTS\s+)?[`"\[]?([A-Za-z_]\w*)?',
    re.I)
_KEYWORDS = {
    "if", "not", "exists", "only", "constraint", "add", "drop", "column", "table",
    "primary", "foreign", "key", "unique", "index", "check", "default", "references",
    "cascade", "using", "set", "alter", "rename", "to", "type", "owner", "temp",
    "temporary", "unlogged", "public", "create",
}


def _ident_ok(name: str | None) -> bool:
    bare = (name or "").split(".")[-1]
    return bool(bare) and bare.lower() not in _KEYWORDS


def _bare(name: str) -> str:
    return name.split(".")[-1]


def _is_migration(path: str) -> bool:
    low = path.lower()
    return "migration" in low or "flyway" in low


def migrations(repo: Repo) -> list[dict]:
    out = []
    for path in sorted(repo.files(".sql", include_tests=True)):
        if not _is_migration(path):
            continue
        base = path.rsplit("/", 1)[-1]
        total = fell_back = 0
        for st in statements(repo.read(path)):
            total += 1
            if st.opaque:
                fell_back += 1
                out += _by_regex(st, repo.id, path, base)
            else:
                out += _by_ast(st, repo.id, path, base)
        if fell_back:
            out.append(fact("SqlParseGap", f"{repo.id}:{path}", repo.id, path, 1,
                            "code", migration=base, statements=total,
                            fell_back_to_regex=fell_back,
                            issue=f"{fell_back} of {total} statements are outside "
                                  f"sqlglot's PostgreSQL support and were read by the "
                                  f"regex fallback",
                            severity="low"))
    return out


def _by_ast(st, repo_id, path, base) -> list[dict]:
    p = st.parsed
    if isinstance(p, exp.Create) and p.args.get("kind") == "TABLE":
        schema = p.this
        if not isinstance(schema, exp.Schema):
            return []
        name = _bare(schema.this.sql())
        if not _ident_ok(name):
            return []
        cols = [{"name": c.name, "type": c.args["kind"].sql() if c.args.get("kind") else ""}
                for c in schema.expressions if isinstance(c, exp.ColumnDef)]
        return [fact("Table", name, repo_id, path, st.line, "code",
                     migration=base, op="create", parsed_by="sqlglot",
                     columns=cols, column_count=len(cols))]
    if isinstance(p, exp.Alter) and p.args.get("kind") == "TABLE":
        name = _bare(p.this.sql())
        if not _ident_ok(name):
            return []
        out = []
        for a in p.args.get("actions") or []:
            # A constraint or an index is not a column, and the regex reported
            # `ADD CONSTRAINT foo` as a column named CONSTRAINT. The AST has a
            # different node type for it, so the distinction is free.
            if isinstance(a, exp.ColumnDef):
                col, op = a.name, "add"
            elif isinstance(a, exp.Drop) and a.args.get("kind") == "COLUMN":
                # sqlglot puts the dropped column under `tables`, not `this` - and
                # `.name` is empty. Reading `.name` lost all four DROP COLUMN changes
                # in the estate on the first pass, which is why the diff exists.
                cols = a.args.get("tables") or []
                col, op = (cols[0].name if cols else ""), "drop"
            else:
                continue
            if not _ident_ok(col):
                continue
            out.append(fact("TableChange", f"{name}.{col}", repo_id, path, st.line,
                            "code", table=name, op=op, column=col, migration=base,
                            parsed_by="sqlglot"))
        return out
    return []


def _by_regex(st, repo_id, path, base) -> list[dict]:
    out = []
    sql = blank_strings(st.sql)
    for m in _CREATE.finditer(sql):
        name = m.group(1)
        if not _ident_ok(name):
            continue
        out.append(fact("Table", _bare(name), repo_id, path,
                        st.line + sql[:m.start()].count("\n"), "code",
                        migration=base, op="create", parsed_by="regex-fallback"))
    for m in _ALTER.finditer(sql):
        tbl, op, col = m.group(1), m.group(2), m.group(3)
        if not (_ident_ok(tbl) and _ident_ok(col)):
            continue
        out.append(fact("TableChange", f"{_bare(tbl)}.{col}", repo_id, path,
                        st.line + sql[:m.start()].count("\n"), "code",
                        table=_bare(tbl), op=op.lower(), column=col, migration=base,
                        parsed_by="regex-fallback"))
    return out
