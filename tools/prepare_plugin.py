#!/usr/bin/env python3
"""Stamp this KB's location into the plugin, so an installed COPY can find it.

`claude plugin install` copies hooks/skills/commands and leaves the knowledge base behind,
so the copy has no way to locate `tools/kb_core.py` or `registry.yaml` on its own. This
writes the absolute path next to the hooks. `E5_KB_ROOT` still overrides it, which is what
a teammate with the KB in a different place will use.

Run before `claude plugin marketplace add` / after moving the KB.
"""
import sys
from pathlib import Path

KB = Path(__file__).resolve().parent.parent
for target in (KB / "plugin" / "hooks" / "kb_root.txt",):
    target.write_text(str(KB) + "\n")
    print(f"stamped {target.relative_to(KB)} -> {KB}")

launcher = KB / "plugin" / "mcp_launch.sh"
launcher.write_text(f'''#!/usr/bin/env bash
# GENERATED by tools/prepare_plugin.py - do not hand-edit.
#
# Lives INSIDE plugin/ so that `claude plugin install` copies it; the KB and tools/ are
# not copied, so the path to the real server is resolved here rather than assumed.
set -euo pipefail
HERE="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
KB="${{E5_KB_ROOT:-}}"
if [ -z "$KB" ] && [ -f "$HERE/hooks/kb_root.txt" ]; then
  KB="$(cat "$HERE/hooks/kb_root.txt")"
fi
if [ -z "$KB" ] || [ ! -f "$KB/tools/mcp_server.py" ]; then
  echo "e5-platform-kb: cannot locate the knowledge base." >&2
  echo "  export E5_KB_ROOT=/path/to/e5-platform-kb" >&2
  exit 1
fi
exec "$KB/tools/mcp_launch.sh" "$@"
''')
launcher.chmod(0o755)
print(f"wrote {launcher.relative_to(KB)}")
