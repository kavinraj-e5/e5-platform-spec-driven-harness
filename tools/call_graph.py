#!/usr/bin/env python3
"""Level 2: what one handler does. A method-level call graph of every Java and Python repo.

    python3 tools/call_graph.py extract [--repo X] [--force]
    python3 tools/call_graph.py status

Writes graph/call-facts.jsonl: one row per method or function, with the calls it makes,
each with its line. `kb_trace` (tools/kb_nav.py) walks it from a handler to the RPCs it
calls and the tasks it sends.

HOW EACH LANGUAGE IS RESOLVED, AND WHY
--------------------------------------
* **Java: tree-sitter with declared-type resolution** (tools/java_ast.py). A receiver's type
  is read from the local, parameter or field declaration; an interface call reaches every
  in-repo implementation. Measured on 2026-11-14: this reaches exactly the outbound sites
  that method-level bytecode and jdtls reach, so it needs no compile and no Java language
  server.
* **Python: pyright**, over the Language Server Protocol (tools/lsp_client.py), using
  `callHierarchy/outgoingCalls`. Python seldom writes a receiver's type down, so a
  syntactic extractor would have to guess callees by name; pyright infers them.

NO GUESSING. A Java call whose receiver cannot be typed (a chain such as `a.b().c()`) is
recorded under `unresolved` by name only, and is never linked to a method with that name.
A call into a library outside the repo is recorded under `ext` with the type it was made on.

WHAT IS READ. The checkout under platform/ (tools/checkouts.py) when it is clean and at the
indexed release; otherwise the release is exported from the bare mirror into a scratch
folder. Either way the facts describe the indexed commit, never local edits. Test sources
and generated protobuf code are skipped. A repo is re-read only when its commit moved.
"""
from __future__ import annotations
import argparse, ast, json, re, subprocess, sys, tempfile, time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import mirror as M

KB = HERE.parent
OUT = KB / "graph" / "call-facts.jsonl"
_GENERATED = re.compile(rb"Generated by the protocol buffer compiler|@javax\.annotation\.Generated|"
                        rb"@jakarta\.annotation\.Generated|@Generated\(\s*value\s*=\s*\"by gRPC")
_SKIP_DIRS = {"test", "tests", "build", "target", ".gradle", ".venv", "venv", "node_modules",
              "__pycache__", ".git", "it", "integrationTest", "testFixtures"}


def _commit(repo: str, branch: str) -> str:
    return subprocess.run(["git", "-C", str(M.CACHE / f"{repo}.git"), "rev-parse",
                           f"refs/heads/{branch}"], capture_output=True, text=True).stdout.strip()


def _tree(repo: str, branch: str, scratch: Path) -> tuple[Path | None, str]:
    """(source root, where it came from) for the indexed commit."""
    try:
        import checkouts
        p = checkouts.clean_paths().get(repo)
        if p:
            return p, "checkout"
    except Exception:
        pass
    dest = scratch / repo
    dest.mkdir(parents=True)
    ar = subprocess.run(["git", "-C", str(M.CACHE / f"{repo}.git"), "archive", "--format=tar",
                         f"refs/heads/{branch}"], capture_output=True)
    if ar.returncode:
        return None, "not mirrored"
    subprocess.run(["tar", "-x", "-C", str(dest)], input=ar.stdout, check=True)
    return dest, "mirror export"


def _sources(root: Path, suffix: str) -> list[Path]:
    out = []
    for f in root.rglob(f"*{suffix}"):
        rel = f.relative_to(root).parts
        if any(p in _SKIP_DIRS for p in rel[:-1]) or f.name.startswith("test_") \
                or f.name.endswith(("Test.java", "Tests.java", "IT.java", "_pb2.py",
                                    "_pb2_grpc.py", "_pb2.pyi")):
            continue
        out.append(f)
    return sorted(out)


# ------------------------------------------------------------------------- Java
def java_rows(repo: str, root: Path) -> list[dict]:
    import java_ast as J
    files = [f for f in _sources(root, ".java") if not _GENERATED.search(f.read_bytes()[:4096])]
    ix = J.JavaAST(root, files)
    rows = []
    for mid, m in ix.methods.items():
        calls, ext, unres = [], [], []
        for c in m["calls"]:
            targets, how = ix.resolve_call(mid, c)
            line = c["line"] + 1
            if how == "name-only":
                unres.append([c["name"], line])
            elif targets:
                calls += [[t, line] for t in targets]
            elif how in ("external-type", "external-static"):
                ext.append([f"{_recv_type(ix, m, c) or c['recv']}.{c['name']}", line])
        rows.append({"kind": "Method", "lang": "java", "repo": repo, "id": mid,
                     "name": m["name"], "owner": m["cls"],
                     "path": str(Path(m["file"]).relative_to(root)),
                     "line": m["start"], "end": m["end"], "calls": calls, "ext": ext,
                     "unresolved": unres, "provenance": "tree-sitter declared-type"})
    return rows


def _recv_type(ix, m, c) -> str | None:
    r = (c["recv"] or "")
    r = r[5:] if r.startswith("this.") else r
    if not re.fullmatch(r"\w+", r):
        return None
    if r in m["locals"]:
        return m["locals"][r]
    for cls in ix.supers(m["cls"]) + [m["cls"].split("$")[0]]:
        f = ix.classes.get(cls, {}).get("fields", {})
        if r in f:
            return f[r]
    return r if r[:1].isupper() else None


# ------------------------------------------------------------------------- Python
def _py_functions(f: Path, root: Path, text: str) -> list[dict]:
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return []
    mod = ".".join(f.relative_to(root).with_suffix("").parts).removesuffix(".__init__")
    lines = text.splitlines()
    out = []

    def walk(node, qual):
        for ch in ast.iter_child_nodes(node):
            if isinstance(ch, (ast.FunctionDef, ast.AsyncFunctionDef)):
                q = f"{qual}.{ch.name}" if qual else ch.name
                m = re.search(rf"\bdef\s+({re.escape(ch.name)})\b", lines[ch.lineno - 1])
                out.append({"id": f"{mod}:{q}", "name": ch.name, "owner": f"{mod}:{qual}" if qual else mod,
                            "line": ch.lineno, "end": ch.end_lineno or ch.lineno,
                            "col": m.start(1) if m else ch.col_offset + 4})
                walk(ch, q)
            elif isinstance(ch, ast.ClassDef):
                walk(ch, f"{qual}.{ch.name}" if qual else ch.name)
    walk(tree, "")
    return out


def _path_of(uri: str) -> str:
    """file URI -> path. pyright percent-encodes (`@` -> %40, space -> %20), so a plain
    prefix strip never matches a path with such a character in it."""
    from urllib.parse import unquote, urlparse
    return unquote(urlparse(uri).path)


def python_rows(repo: str, root: Path, lsp_cmd: str) -> list[dict]:
    import lsp_client as L
    files = _sources(root, ".py")
    funcs, texts = {}, {}
    for f in files:
        texts[f] = f.read_text(errors="replace")
        for fn in _py_functions(f, root, texts[f]):
            funcs[(str(f.resolve()), fn["line"])] = (f, fn)
    lsp = L.LSP([lsp_cmd, "--stdio"], root)
    rows = []
    try:
        for f in files:
            lsp.open(f, texts[f])
        rroot = str(root.resolve())
        for (fpath, _line), (f, fn) in funcs.items():
            calls, ext = [], []
            try:
                res = lsp.outgoing(f, fn["line"] - 1, fn["col"])
            except Exception:
                res = []
            for oc in res:
                to = oc["to"]
                tpath = _path_of(to["uri"])
                tline = to["selectionRange"]["start"]["line"] + 1
                for fr in oc.get("fromRanges", []):
                    line = fr["start"]["line"] + 1
                    hit = funcs.get((tpath, tline))
                    if hit and tpath.startswith(rroot):
                        calls.append([hit[1]["id"], line])
                    elif tpath.startswith(rroot):
                        pass   # a class or a lambda in the repo: not a function we index
                    else:
                        src = Path(tpath).stem if tpath.endswith((".py", ".pyi")) else ""
                        ext.append([f"{src}.{to['name']}" if src else to["name"], line])
            rows.append({"kind": "Method", "lang": "python", "repo": repo, "id": fn["id"],
                         "name": fn["name"], "owner": fn["owner"],
                         "path": str(f.relative_to(root)), "line": fn["line"], "end": fn["end"],
                         "calls": sorted(calls, key=lambda x: x[1]),
                         "ext": sorted(ext, key=lambda x: x[1]), "unresolved": [],
                         "provenance": "pyright"})
    finally:
        lsp.close()
    return rows


# ------------------------------------------------------------------------- driver
def _existing() -> dict[str, list[dict]]:
    by = {}
    if OUT.is_file():
        for l in OUT.open():
            if l.strip():
                d = json.loads(l)
                by.setdefault(d["repo"], []).append(d)
    return by


def extract(only: list[str], force: bool) -> int:
    _, repos = M.registry()
    old = _existing()
    lsp_cmd = None
    import lsp_client as L
    keep: dict[str, list[dict]] = {}
    fails = 0
    with tempfile.TemporaryDirectory(prefix="e5-callgraph-") as tmp:
        for r in repos:
            rid, lang, br = r["id"], r.get("language"), r.get("branch", "")
            if lang not in ("java", "python") or (only and rid not in only):
                if rid in old:
                    keep[rid] = old[rid]
                continue
            commit = _commit(rid, br)
            if not commit:
                print(f"  {rid:32} SKIP  not mirrored"); continue
            if not force and old.get(rid) and old[rid][0].get("commit") == commit:
                keep[rid] = old[rid]
                print(f"  {rid:32} same  {len(old[rid])} methods @ {commit[:8]}"); continue
            if lang == "python":
                lsp_cmd = lsp_cmd or L.find_pyright()
                if not lsp_cmd:
                    print(f"  {rid:32} SKIP  pyright-langserver not installed "
                          f"(npm i -g pyright, or pipx install pyright)")
                    fails += 1
                    if rid in old:
                        keep[rid] = old[rid]
                    continue
            t0 = time.time()
            root, how = _tree(rid, br, Path(tmp))
            if root is None:
                print(f"  {rid:32} SKIP  {how}"); continue
            try:
                rows = java_rows(rid, root) if lang == "java" else python_rows(rid, root, lsp_cmd)
            except Exception as e:  # one repo's failure must not lose the others' facts
                print(f"  {rid:32} FAIL  {type(e).__name__}: {str(e)[:100]}"); fails += 1
                if rid in old:
                    keep[rid] = old[rid]
                continue
            for x in rows:
                x.update(branch=br, commit=commit)
            keep[rid] = rows
            n_calls = sum(len(x["calls"]) for x in rows)
            n_un = sum(len(x["unresolved"]) for x in rows)
            print(f"  {rid:32} ok    {len(rows)} methods, {n_calls} resolved calls, "
                  f"{n_un} unresolved ({how}, {lang}) [{time.time() - t0:.0f}s]")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    tmp_out = OUT.with_suffix(".tmp")
    with tmp_out.open("w") as fh:
        for rid in sorted(keep):
            for x in sorted(keep[rid], key=lambda x: (x["path"], x["line"], x["id"])):
                fh.write(json.dumps(x, sort_keys=True) + "\n")
    tmp_out.replace(OUT)
    total = sum(len(v) for v in keep.values())
    print(f"\n{total} methods across {len(keep)} repos -> {OUT.relative_to(KB)}")
    return 1 if fails else 0


def status() -> int:
    for rid, rows in sorted(_existing().items()):
        r = rows[0]
        print(f"  {rid:32} {r['lang']:7} {len(rows):6} methods  {r['branch']} @ {r['commit'][:8]}"
              f"  ({r['provenance']})")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    ex = sub.add_parser("extract")
    ex.add_argument("--repo", action="append", default=[])
    ex.add_argument("--force", action="store_true")
    sub.add_parser("status")
    a = ap.parse_args()
    return extract(a.repo, a.force) if a.cmd == "extract" else status()


if __name__ == "__main__":
    sys.exit(main())
